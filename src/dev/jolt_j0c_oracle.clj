;; J0c round 2: write the JVM oracle for the jolt parser corpus
;; (docs/design/yin.repl-jolt-implementation.md §7.8).
;;
;;   clojure -M:dev -m jolt-j0c-oracle
;;
;; Reads test/yang/python/antlr/fixtures/jolt_j0c_corpus.edn and writes
;; jolt_j0c_oracle.edn beside it, using only the repo's own JVM path: the
;; generated Java recognizers through yang.python.antlr.parser, the JVM
;; yang.antlr.cst and the shared yang.antlr.export/packet code. For each entry,
;; its packet (unit [:unit 0], a fresh worker) and its cst/first-failure; for
;; each probe text, repl-probe/probe's answer and every cst/first-failure call
;; the probe made, in order. jolt output is never an input here.
(ns jolt-j0c-oracle
  (:require
    [clojure.edn :as edn]
    [clojure.pprint :as pprint]
    [yang.antlr.cst :as cst]
    [yang.python.antlr.parser :as parser]
    [yang.python.antlr.repl-probe :as probe]))


(def corpus-path "test/yang/python/antlr/fixtures/jolt_j0c_corpus.edn")
(def oracle-path "test/yang/python/antlr/fixtures/jolt_j0c_oracle.edn")


(defn- entry
  [{:keys [id source]}]
  {:id id,
   :source source,
   :packet (parser/parse-source (parser/make-worker) [:unit 0] source),
   :first-failure (cst/first-failure (parser/make-worker) source)})


(defn- probe-entry
  [text]
  (let [calls (volatile! [])
        first-failure cst/first-failure
        answer (with-redefs [cst/first-failure
                             (fn [worker source]
                               (let [r (first-failure worker source)]
                                 (vswap! calls conj [source r])
                                 r))]
                 (probe/probe text))]
    {:text text, :probe answer, :first-failure-calls @calls}))


(defn -main
  [& _]
  (let [{:keys [entries], probes :probe} (edn/read-string (slurp corpus-path))
        oracle {:host :jvm,
                :grammar-id parser/grammar-id,
                :written-by "src/dev/jolt_j0c_oracle.clj",
                :entries (mapv entry entries),
                :probe (mapv probe-entry probes)}]
    (spit oracle-path
          (str ";; GENERATED by `clojure -M:dev -m jolt-j0c-oracle` from\n"
               ";; jolt_j0c_corpus.edn on the JVM. Do not edit by hand, and never\n"
               ";; regenerate it from another host's output.\n"
               (with-out-str (pprint/pprint oracle))))
    (println "wrote" oracle-path (count entries) "entries," (count probes) "probe texts")
    (shutdown-agents)))
