;; Generate test/yang/latte_oracle/manifest.edn from the pinned latte-kernel
;; git dependency (see deps.edn :test alias, sha 86fca0d1).
;; Run: clj -M -m latte-oracle-manifest  (after adding src/dev to classpath)
(ns latte-oracle-manifest
  (:require [clojure.java.io :as io]
            [clojure.tools.reader :as r]
            [clojure.tools.reader.reader-types :as rt]
            [clojure.pprint :as pp]))


(def namespaces
  '[latte_kernel.defenv latte_kernel.nbe latte_kernel.norm
    latte_kernel.presyntax latte_kernel.proof latte_kernel.syntax
    latte_kernel.typing latte_kernel.unparser latte_kernel.utils])


(defn read-forms
  [f]
  (let [pr (rt/source-logging-push-back-reader (java.io.PushbackReader. (io/reader f)) 1 (str f))]
    (let [ns-form (r/read {:eof ::eof} pr)
          aliases (atom {})
          _ (when (and (seq? ns-form) (= 'ns (first ns-form)))
              (loop [xs (flatten (rest ns-form))]
                (when (seq xs)
                  (if (= :as (first xs))
                    (do (swap! aliases assoc (second xs) 'dummy)
                        (recur (drop 2 xs)))
                    (recur (next xs))))))
          am (zipmap (keys @aliases)
                     (map #(symbol "latte_kernel" (name %)) (keys @aliases)))]
      (binding [r/*alias-map* am]
        (loop [acc []]
          (let [form (r/read {:read-cond :allow :features #{:clj} :eof ::eof} pr)]
            (if (= form ::eof) acc (recur (conj acc form)))))))))


(defn manifest
  []
  (for [ns-sym namespaces]
    (let [res (io/resource (str (clojure.string/replace (name ns-sym) "." "/") ".cljc"))]
      (assert res (str "cannot find source for " ns-sym))
      (for [form (read-forms res)
            :when (and (seq? form) (contains? #{'defn 'def 'defn-} (first form)))]
        (let [kind (first form)
              name (second form)]
          {:ns ns-sym, :kind kind, :name name
           :source (:ns (meta form))})))))


(let [entries (into [] (mapcat identity) (manifest))
      out (str ";; GENERATED by src/dev/latte_oracle_manifest.clj from the pinned\n"
               ";; latte-kernel git dependency (deps.edn :test, sha 86fca0d1).\n"
               ";; {:ns ... :kind defn|def|defn- :name ...} one entry per top-level binding.\n"
               (with-out-str (pp/pprint entries)))]
  (io/make-parents "test/yang/latte_oracle/manifest.edn")
  (spit "test/yang/latte_oracle/manifest.edn" out)
  (println "wrote" (count entries) "entries"))
