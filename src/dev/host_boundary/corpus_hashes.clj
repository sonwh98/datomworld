(ns host-boundary.corpus-hashes
  "The corpus hash set of dao.stream.host-boundary.md H0 (d): the SHA-256
   of every file under the Jing corpus (test/resources/dao/jing) and the
   codec wire fixtures (test/fixtures/codec), which H1-H4 must keep
   byte-identical.

   Run from the repo root with babashka:
     bb src/dev/host_boundary/corpus_hashes.clj [--check]
   writes docs/design/host-boundary/corpus-sha256.edn; --check writes
   nothing and exits 1 when a file's bytes, or the file set, differ from
   the committed hash set. dao.host.gate-test asserts the same on the JVM
   lane."
  (:require
    [babashka.fs :as fs]
    [clojure.edn :as edn]
    [clojure.pprint :as pp]
    [clojure.string :as str]))


(def roots ["test/resources/dao/jing" "test/fixtures/codec"])
(def out-file "docs/design/host-boundary/corpus-sha256.edn")


(defn sha-256
  [path]
  (let [d (java.security.MessageDigest/getInstance "SHA-256")]
    (apply str (map #(format "%02x" (bit-and % 0xff))
                    (.digest d (fs/read-all-bytes path))))))


(defn hash-set*
  []
  {:algorithm "SHA-256"
   :regenerate "bb src/dev/host_boundary/corpus_hashes.clj"
   :roots roots
   :files (into (sorted-map)
                (for [r roots
                      p (fs/glob r "**")
                      :when (fs/regular-file? p)
                      :let [f (str/replace (str p) "\\" "/")]]
                  [f (sha-256 p)]))})


(defn render
  [m]
  (str ";; Generated by src/dev/host_boundary/corpus_hashes.clj (host-boundary H0).\n"
       ";; Do not edit by hand; H1-H4 keep these bytes identical.\n"
       (with-out-str (pp/pprint m))))


(defn -main
  [& args]
  (let [m (hash-set*)
        text (render m)]
    (println (count (:files m)) "files")
    (if (some #{"--check"} args)
      (let [committed (when (fs/exists? out-file) (edn/read-string (slurp out-file)))]
        (if (= (:files committed) (:files m))
          (println "corpus identical to" out-file)
          (do (println "CORPUS DIFFERS from" out-file)
              (doseq [f (sort (into (set (keys (:files m))) (keys (:files committed))))
                      :when (not= (get (:files m) f) (get (:files committed) f))]
                (println " " f))
              (System/exit 1))))
      (spit out-file text))))


(when (= *file* (System/getProperty "babashka.file"))
  (apply -main *command-line-args*))
