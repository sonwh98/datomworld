(ns yang.typescript.antlr.cst
  "The TypeScript parser worker (docs/design/yang.typescript.md section 5): the
   grammars-v4 typescript grammar, patched by `ts-g4-1`, as a profile over the
   generic `yang.antlr.cst` worker. The generated recognizers come from
   `bb gen:antlr` (antlr/typescript/manifest.edn); the JVM is the only local
   target. The entry rule is `program`.

   The dialect is worker configuration read by a semantic predicate in the
   parser base class: in `:ts` a `<...>` followed by `(` is type arguments, in
   `:js` it is relational. Template-literal depth and regex-versus-division
   context are tracked by the lexer base class."
  (:require
    [yang.antlr.cst :as cst]
    [yang.stage :as stage])
  (:import
    (yang.typescript.antlr.gen
      TypeScriptLexer
      TypeScriptParser)))


(def grammar-id
  "grammars-v4 typescript at its pinned revision, patched by ts-g4-1,
   generated by ANTLR 4.13.2."
  "grammars-v4/typescript@85e2dd1779ce556111ef98ead5d62a9858e95599+ts-g4-1 antlr-4.13.2")


(defn profile
  "The grammar profile for `dialect`, `:ts` or `:js`."
  [dialect]
  (assert (#{:ts :js} dialect) "dialect is :ts or :js")
  {:grammar-id grammar-id,
   :make-lexer (fn [cs] (TypeScriptLexer. cs)),
   :make-parser (fn [ts]
                  (doto (TypeScriptParser. ts)
                    (.setTsDialect (= :ts dialect)))),
   :start (fn [^TypeScriptParser p] (.program p))})


(defn make-worker
  "A worker for `dialect` (default `:ts`); a worker serves one dialect."
  ([] (make-worker :ts))
  ([dialect] (cst/make-worker (profile dialect))))


(defn parse-source
  "Parse one complete source string as unit `unit`: the CST packet."
  ([source] (parse-source (make-worker) [:unit 0] source))
  ([worker unit source] (cst/parse-unit worker unit source)))


(defn- with-options
  "`transform` with every packet it writes carrying `:yang.cst/options`,
   `{:dialect dialect}`, so the lowering reads the dialect from the packet."
  [transform dialect]
  (fn [state event]
    (let [[state' outputs] (transform state event)]
      [state'
       (mapv (fn [[port value]]
               [port
                (if (map? value)
                  (assoc value :yang.cst/options {:dialect dialect})
                  value)])
             outputs)])))


(defn open-stage
  "A parser stage reading source events from `source-stream` and writing
   CST packets to `cst-stream`, with its own worker for `dialect` (default
   `:ts`). Every packet carries `:yang.cst/options {:dialect dialect}`."
  ([source-stream cst-stream] (open-stage source-stream cst-stream :ts))
  ([source-stream cst-stream dialect]
   (assoc (stage/open source-stream {:cst cst-stream} {})
          ::transform (with-options (cst/parse-transform (make-worker dialect))
                        dialect))))


(defn step-stage
  [s]
  (stage/step s (::transform s)))
