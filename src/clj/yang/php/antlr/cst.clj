(ns yang.php.antlr.cst
  "The PHP parser worker (docs/design/yang.php.md section 6): the
   grammars-v4 php grammar profile over the generic `yang.antlr.cst` worker.
   The generated recognizers come from `bb gen:antlr` (antlr/php/manifest.edn);
   the JVM is the only local target. The entry rule is `htmlDocument`.

   The grammar's non-standard generics (`typeParameterListInBrackets`, the
   `<: ... :>` brackets) are not PHP: a parse that uses them is refused as
   `{:yang.php/not-php :generics}` rather than exported."
  (:require
    [yang.antlr.cst :as cst])
  (:import
    (yang.php.antlr.gen
      PhpLexer
      PhpParser)))


(def grammar-id
  "grammars-v4 php at its pinned revision, generated by ANTLR 4.13.2."
  "grammars-v4/php@85e2dd1779ce556111ef98ead5d62a9858e95599 antlr-4.13.2")


(def profile
  {:grammar-id grammar-id,
   :make-lexer (fn [cs] (PhpLexer. cs)),
   :make-parser (fn [ts] (PhpParser. ts)),
   :start (fn [^PhpParser p] (.htmlDocument p))})


(defn make-worker
  []
  (cst/make-worker profile))


(defn- generics?
  [pk]
  (boolean (some #(= "typeParameterListInBrackets" (:rule %))
                 (:yang.cst/nodes pk))))


(defn parse-source
  "Parse one complete PHP source string as unit `unit`: the CST packet, or
   `{:yang.php/not-php :generics}` when the parse uses the grammar's generics
   extension."
  ([source] (parse-source (make-worker) [:unit 0] source))
  ([worker unit source]
   (let [pk (cst/parse-unit worker unit source)]
     (if (generics? pk)
       {:yang.php/not-php :generics}
       pk))))
